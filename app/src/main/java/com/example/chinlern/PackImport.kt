package com.example.chinlern

import org.json.JSONObject

object PackImport {
    data class Preview(val name: String, val words: List<Word>)
    fun parse(raw: String): Preview {
        require(raw.toByteArray(Charsets.UTF_8).size <= 2_000_000) { "Ответ слишком большой: максимум 2 МБ." }
        var text = raw.trim().removePrefix("\uFEFF").trim()
        require(text.isNotEmpty()) { "Вставьте ответ модели или выберите файл." }
        if (!text.startsWith("{") && !text.startsWith("[")) {
            val blocks = Regex("(?ms)^```(?:json)?[ \\t]*\\r?\\n(.*?)^```[ \\t]*$").findAll(text).toList()
            require(blocks.size == 1) { "Нужен JSON или один блок ```json. Скопируйте только набор, без нескольких вариантов ответа." }
            text = blocks.single().groupValues[1].trim()
        }
        val words = try {
            val tokenizer = org.json.JSONTokener(text)
            val value = tokenizer.nextValue()
            require(value is JSONObject || value is org.json.JSONArray) { "Нужен объект или массив JSON." }
            require(tokenizer.nextClean() == '\u0000') { "После JSON есть лишний текст. Скопируйте только набор." }
            StudyStore.decodeWords(text)
        } catch (e: Exception) {
            throw IllegalArgumentException("Проверьте набор: ${e.message ?: "неверный JSON"}", e)
        }
        val name = if (text.startsWith("{")) JSONObject(text).optString("name", "Новый набор") else "Новый набор"
        return Preview(name.take(80), words)
    }
    val prompt = """
        Подготовь учебный набор китайских слов для приложения Chinlearn по моему списку ниже.
        Ответ: один корректный JSON-объект, без пояснений и Markdown, который можно скопировать или сохранить в файл .json (UTF-8).

        Формат:
        {"name":"Название набора","words":[{"hanzi":"水","pinyin":"shuǐ","numbered":"shui3","meanings":["вода"],"alternatives":[],"hint":""}]}

        Правила:
        1. name — короткое название до 80 символов. words — от 1 до 2000 карточек. Не добавляй слова вне моего списка. Убери дубликаты hanzi.
        2. hanzi — слово или радикал (до 30 знаков), без пиньиня, скобок и списка вариантов через слеш.
        3. pinyin — корректный пиньинь со знаками тонов. numbered — то же произношение с цифрой 1–5 после КАЖДОГО слога, слоги через пробел. Нейтральный тон — 5. Пример: nǐ hǎo / ni3 hao3; nǚ / nü3; xuésheng / xue2 sheng5. Используй словарные тоны, без изменений тонов в связной речи.
        4. meanings — непустой массив кратких русских переводов и точных синонимов. Один перевод — одна строка массива, без нумерации. Каждый до 200 символов. Выбери одно чтение/значение неоднозначного слова с учётом моего контекста; если контекста недостаточно, сначала уточни его, не выдумывай.
        5. alternatives — необязательный массив допустимых написаний именно этой карточки. Для радикала 水 допустима форма 氵, но не подставляй радикальные формы вместо знаков в обычных словах. Альтернативы должны соответствовать выбранному значению и произношению. Не смешивай разные слова. До 30 вариантов, каждый до 30 знаков.
        6. hint — необязательная краткая подсказка после ответа (до 2000 символов). Не выдумывай этимологию или порядок черт.
        7. distractors можно не указывать: приложение добавит неверные варианты само. Если указываешь — массив минимум из трёх разных неверных написаний, исключая hanzi и alternatives.
        8. id необязателен: приложение использует hanzi. Если задаёшь id — уникальная непустая строка до 100 символов без двоеточия.
        9. Проверь переводы, соответствие пиньиня и тонов, корректность JSON. Используй двойные кавычки, без комментариев и завершающих запятых. Размер ответа — до 2 МБ.

        Мои слова и контекст:
        [Вставьте сюда список слов, тему, уровень и нужные значения.]
    """.trimIndent()
}
